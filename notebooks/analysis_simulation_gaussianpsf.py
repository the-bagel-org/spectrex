def _corr(a, b):
    """Correlation over finite, positive elements (robust to NaNs/zeros)."""
    a = np.asarray(a, float)
    b = np.asarray(b, float)
    m = np.isfinite(a) & np.isfinite(b) & (a > 0) & (b > 0)
    if m.sum() < 3:
        return float("nan")
    return float(np.corrcoef(a[m], b[m])[0, 1])


def _safe_norm(img, kind="log", percs=(20, 99.5)):
    """Display norm that never raises on degenerate (e.g. background) ranges."""
    vmin, vmax = np.nanpercentile(
        np.where(np.isfinite(img), img, np.nan), percs
    )
    if not (np.isfinite(vmin) and np.isfinite(vmax) and vmax > vmin):
        return colors.Normalize(vmin=np.nanmin(img), vmax=np.nanmax(img))
    if kind == "log":
        lo = max(vmin, 1e-3)
        if vmax <= lo:
            return colors.Normalize(vmin=vmin, vmax=vmax)
        return colors.LogNorm(vmin=lo, vmax=vmax)
    return colors.Normalize(vmin=vmin, vmax=vmax)


def make_review_figures(
    res, band, outdir="figures", close_figures=True, seed: int | None = None
) -> list[str] | tuple[list[Figure], list[str]]:
    """Write the four standard review figures for one band.

    * fig1: full-frame data / model / residual
    * fig2: zoomed segment of one bright isolated source's trace
    * fig3: recovered vs true (Kurucz) spectrum for 4 isolated sources
    * fig4: observed (direct extraction x sensitivity) vs model prediction
    * fig5: grism image snippet per source

    Returns the list of saved file paths.
    """
    os.makedirs(outdir, exist_ok=True)
    obs = res.observed_grism
    mod = res.model_grism
    resid = res.residual_image
    shape = obs.shape
    wav = res.λ_AA
    saved = []

    figures = []

    # ---- Fig 1: full-frame data / model / residual ----
    fig, axes = plt.subplots(1, 3, figsize=(16, 5), sharex=True, sharey=True)
    for ax, img, title in zip(
        axes,
        [obs, mod, resid],
        ["data", "model", "residual (obs-model)/p99(obs)"],
    ):
        if title.startswith("residual"):
            im_ = ax.imshow(
                img,
                origin="lower",
                cmap="RdBu",
                norm=colors.CenteredNorm(vcenter=0, halfrange=0.05),
            )
        else:
            vmin, vmax = np.nanpercentile(obs, [16, 84])
            im_ = ax.imshow(
                img,
                origin="lower",
                cmap="gray",
                norm=colors.AsinhNorm(vmin=vmin, vmax=vmax),
            )
        fig.colorbar(im_, ax=ax)
        ax.set_title(title, fontsize="large", fontweight="bold")
    plt.tight_layout()
    p = os.path.join(outdir, f"fig1_{band}.png")
    fig.savefig(p, bbox_inches="tight")
    saved.append(p)
    figures.append(fig)

    # ---- Fig 2: zoomed trace *segment* for a bright isolated source ----
    iso = res.other["is_isolated"]
    flux = res.observed_fluxes
    cand = np.where(iso)[0]
    k = int(cand[np.argmax(flux[cand])])
    op = res.operator
    n_pix = shape[0] * shape[1]
    pix = np.asarray(op._trace_indices[k, 0])
    valid = np.where(pix < n_pix)[0]
    # central ~25% of the (valid) trace, so the window is a real zoom
    lo = valid[len(valid) // 2 - len(valid) // 8]
    hi = valid[len(valid) // 2 + len(valid) // 8]
    seg = pix[lo : hi + 1]
    rows = seg // shape[1]
    cols = seg % shape[1]
    win = 6
    yy0 = max(0, int(rows.min()) - win)
    yy1 = min(shape[0], int(rows.max()) + win + 1)
    xx0 = max(0, int(cols.min()) - win)
    xx1 = min(shape[1], int(cols.max()) + win + 1)
    cd = obs[yy0:yy1, xx0:xx1]
    cm = mod[yy0:yy1, xx0:xx1]
    cr = resid[yy0:yy1, xx0:xx1]
    fig, axes = plt.subplots(1, 3, figsize=(12, 4.2), sharex=True, sharey=True)
    norm = _safe_norm(cd)
    for ax, img, t in zip(axes, [cd, cm, cr], ["Data", "Model", "Residual"]):
        if t == "Residual":
            im = ax.imshow(
                img,
                origin="lower",
                cmap="RdBu",
                norm=colors.CenteredNorm(vcenter=0, halfrange=0.05),
            )
        else:
            im = ax.imshow(
                np.where(np.isfinite(img) & (img > 0), img, 1e-10),
                origin="lower",
                cmap="gray",
                norm=norm,
            )
        plt.colorbar(im, ax=ax, orientation="horizontal")
        ax.set_title(t)
    plt.tight_layout()
    plt.suptitle(
        f"{band} — source {k} (zoomed trace segment)",
        y=1.05,
        fontsize="large",
        fontweight="bold",
    )
    p = os.path.join(outdir, f"fig2_{band}.png")
    fig.savefig(p, bbox_inches="tight")
    saved.append(p)
    figures.append(fig)

    ### COMMON TO Fig 3:5
    orig = res.other["original_spectra"]
    sp = res.model_spectra
    idx = np.where(iso)[0]
    if seed is None:
        picks = list(idx[np.argsort(flux[idx])[::-1][:4]])
    else:
        rng = np.random.default_rng(seed)
        picks = list(rng.choice(idx, 4, replace=False))

    # ---- Fig 3: recovered vs true (Kurucz) spectrum ----

    fig, axes = plt.subplots(2, 4, figsize=(18, 8), sharex=True)
    for j, kk in enumerate(picks):
        rec = sp[kk]
        tru = orig[kk]
        cont = np.median(tru[tru > 0])
        rec_med = np.median(rec[rec > 0])
        rec_s = rec * (cont / rec_med) if rec_med > 0 else rec
        c = _corr(rec_s / cont, tru / cont)
        axes[0, j].plot(wav, tru / cont, "k-", lw=1.4, label="true (Kurucz)")
        axes[0, j].plot(wav, rec_s / cont, "C1--", lw=1.2, label="recovered")
        axes[0, j].set_title(f"src {kk}  corr={c:.2f}")
        axes[0, j].legend(fontsize=7)
        axes[1, j].plot(wav, (rec_s - tru) / cont, color="C1", lw=1.0)
        axes[1, j].axhline(0, color="k", lw=0.6)
        axes[1, j].set_xlabel(
            "wavelength [A]", fontsize="large", fontweight="bold"
        )
        if j == 0:
            axes[0, j].set_ylabel(
                "flux / continuum", fontsize="large", fontweight="bold"
            )
            axes[1, j].set_ylabel(
                "resid / continuum", fontsize="large", fontweight="bold"
            )
    fig.suptitle(
        f"{band}: reconstructed vs true spectrum (4 isolated sources)",
        fontsize="large",
        fontweight="bold",
    )
    plt.tight_layout()
    p = os.path.join(outdir, f"fig3_{band}.png")
    fig.savefig(p, bbox_inches="tight")
    saved.append(p)
    figures.append(fig)

    # ---- Fig 4: observed (direct extraction x sensitivity) vs model ----
    # direct_extract_source returns image flux = spectrum x sensitivity; the
    # model prediction in the same units is model_spectra x sensitivity.
    direct = res.other["isolated_direct_spectra"]
    sens = res.sensitivity_curves["+1"]
    model_flux = sp * sens[None, :]
    true_flux = orig * sens[None, :]

    fig, axes = plt.subplots(2, 4, figsize=(18, 8), sharex=True)
    for j, kk in enumerate(picks):
        obs_k = direct[kk]
        mod_k = model_flux[kk]
        tru_k = true_flux[kk]
        on = np.nanmedian(obs_k[obs_k > 0]) or 1.0
        mn = np.nanmedian(mod_k[mod_k > 0]) or 1.0
        tn = np.nanmedian(tru_k[tru_k > 0]) or 1.0
        c = _corr(obs_k / on, mod_k / mn)
        axes[0, j].plot(wav, tru_k / tn, "k-", lw=1.3, label="true x sens")
        axes[0, j].plot(wav, mod_k / mn, "C0-", lw=1.1, label="model x sens")
        axes[0, j].plot(
            wav, obs_k / on, "C1.", ms=3, alpha=0.7, label="observed (direct)"
        )
        axes[0, j].set_title(f"src {kk}  corr(obs,model)={c:.2f}")
        axes[0, j].legend(fontsize=7)
        axes[1, j].plot(wav, (obs_k / on) - (mod_k / mn), color="C1", lw=1.0)
        axes[1, j].axhline(0, color="k", lw=0.6)
        axes[1, j].set_xlabel("wavelength [A]")
        if j == 0:
            axes[0, j].set_ylabel(
                "(flux x sens) / med", fontsize="large", fontweight="bold"
            )
            axes[1, j].set_ylabel(
                "obs - model (norm)", fontsize="large", fontweight="bold"
            )
    fig.suptitle(
        f"{band}: observed (direct x sensitivity) vs model in likelihood units",
        fontsize="large",
        fontweight="bold",
    )
    plt.tight_layout()
    p = os.path.join(outdir, f"fig4_{band}.png")
    fig.savefig(p, bbox_inches="tight")
    figures.append(fig)
    saved.append(p)

    # ---- Fig 5: grism snippets per source
    img = {
        "data": res.observed_grism,
        "model": res.model_grism,
        "residual": res.residual_image,
    }
    fig, axes = plt.subplots(
        3, 5, figsize=(18, 6), width_ratios=[1, 1, 1, 1, 0.08]
    )
    for axes_, kind in zip(axes, img):
        image = img[kind]
        _im = None
        for ax, i in zip(axes_, picks):
            subimage = trace_snippet(image, res.operator, i, win=50)
            if kind == "residual":
                norm = colors.CenteredNorm(vcenter=0, halfrange=0.05)
                cmap = "coolwarm"
            else:
                norm = _safe_norm(image, "linear", percs=(80, 99))
                cmap = "magma"
            _im = ax.imshow(
                subimage + 1e-5, origin="lower", cmap=cmap, norm=norm
            )
        plt.colorbar(_im, cax=axes_[-1])
    for i, ax in zip(picks, axes[0]):
        ax.set_title(f"Source {i}", fontsize="large", fontweight="bold")
    for kind_, ax_ in zip(img, axes[:, 0]):
        ax_.set_ylabel(kind_, fontsize="large", fontweight="bold")
    for ax in axes[:-1, :-1].ravel():
        plt.setp(ax.get_xticklabels(), visible=False)
    for ax in axes[:, 1:-1].ravel():
        plt.setp(ax.get_yticklabels(), visible=False)
    p = os.path.join(outdir, f"fig5_{band}.png")
    fig.savefig(p, bbox_inches="tight")
    figures.append(fig)
    saved.append(p)

    if not close_figures:
        return figures, saved
    else:
        [plt.close(fig) for fig in figures]
        return saved


def make_all_review_figures(
    bands=("F115W", "F150W", "F200W"), outdir="figures", **kwargs
):
    """Run every band and write all review figures.

    Takes a few minutes (one fit per band).
    """
    os.makedirs(outdir, exist_ok=True)
    for band in bands:
        print(f"[review] {band} ...", flush=True)
        res = run_band(band)
        make_review_figures(res, band, outdir=outdir, **kwargs)


