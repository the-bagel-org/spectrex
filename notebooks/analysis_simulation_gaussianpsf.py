"""This script analyzes the performance of the Gaussian PSF operator on simulated data (simulated_data/output, generated with simulated_data/simulate.py).

This script can be run through a REPL kernel or as a standalone script.

# Running Spectrex on simulated data

In this notebook we run Spectrex on realistic simulated NIRISS/GR150C WFSS data
(generated by `simulated_data/simulate.py` (which uses a Gaussian) to demonstrate extraction.

These simulations are **not** produced by Spectrex's own forward operator, so the
operator must be built to match the *same* grism calibration the simulations used
(the CRDS `specwcs` files shipped alongside the data), and must include the PSF
convolution the simulations apply. Both fixes live in small notebook-local helper
classes below (`CRDSConfig`, `PSFOperator`) so the library is left untouched.

## Looking at the simulated data `simulated_data/output...`

- folder contains simulated data with a Gaussian PSF profile (FWHM 1.6 px, slightly undersampled).
- For each set we have F115W, F150W, and F200W outputs: `sim_GR150C_<band>_direct.fits`, `sim_GR150C_<band>_grism.fits`
- `truth_catalog.ecsv` contains the positions and fluxes of the simulated sources (and additional labels for validation)

### Analysis tools and functions

We defined conveniently a few classes to help store and manipulate our configuration and results.

### CRDSConfig

The `CRDSConfig` class is a subclass of `InstrumentConfig` that drives a CRDS ``specwcs`` trace correctly.
It is a temporary patch that fixes the Angstrom→micron units and the (col,row)↔(row,col) convention swap;

### PSFOperator

The `PSFOperator` class is a subclass of `JAXOperator` that includes a (Gaussian) PSF convolution.

The internals of Spectrex did not consider the convolution of a PSF, so the
`PSFOperator` is a temporary patch that fixes this.

### SimulationAnalysisConfig & SimulationAnalysisResult

- `SimulationAnalysisConfig`: holds the configuration analysis for a set of bands. This is common across all bands for our simulated data.
- `SimulationAnalysisResult`: holds the results of a single band analysis.

### SpectralBasis

A simple interface to the spectra from the basis library.

## Analysis Pipeline

- `run_band`: is the main analysis function for a given band. It builds a PSF-aware, CRDS-driven operator and fit one grism image and returns a SimulationAnalysisResult`.

###  Pipeline schematics

To analyze a band image (e.g. F150W), we do the following:
- prepare the data
    - we load the simulated band image, we have only order = "+1" here. --> gaussian psf: sigma_psf = fwhm / 2.355 from header
    - we load the source catalog to get the positions of the sources
    - we setup the mapping of tracings for this specific band using CRDS information (wcs) -- `get_grismtrace_from_crds`
    - we get the wavelength range for the order (+1 only here) in the image to help define the wavelength grid for PCA and sensitivity curves
    - Get the sensitivity curve for this band and these wavelengths `get_sensitivity_curve(which_band, wavelengths)`
- prepare the model
    - set the InstrumentConfig that drives a CRDS specwcs trace correctly.
    - Reload the PCA basis from disk (here 10PCs from kurucz atmospheres at R=140, and normalized to eigenvalues)
    - Build the `JaxOperator` (FIXME: numpy operations within)
    - Build the PSF operator `op =PSFOperator(...)` (Gaussian convolution) composed with the previous one.
    - Setup the Solver `JaxProximalSolver`
- Fit the model
    - we internally scale the fluxes to the 90th flux percentile (1e22 -> 1)
    - Solve the optimization problem using the solver `a = solver.solve()` (ravelled images)
- Extract the solution
    - image is the `model = op.apply(a).reshape(...)`
    - extract the spectra `spectra = a.reshape(-1, basis.n_components) @ basis.components.T`
- Analysis/statistics

"""

