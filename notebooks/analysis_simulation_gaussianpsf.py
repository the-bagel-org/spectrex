@dataclass
class SpectralBasis:
    """A class to manipulate the spectral basis (original spectra)."""

    original_spectra_path: Path
    """Original spectra path (CSV format, last row = wavelength in Angstrom)"""

    def __post_init__(self):
        data = np.loadtxt(
            self.original_spectra_path, delimiter=",", dtype=float
        )
        self._wave = np.asarray(data[-1], dtype=float)  # Angstrom (last row)
        self._spectra = np.asarray(
            data[:-1], dtype=float
        )  # (n_templates, n_wave)
        # enforce ascending wavelength order
        _idx = np.argsort(self._wave)
        self._wave = self._wave[_idx]
        self._spectra = self._spectra[:, _idx]

    @property
    def λ_AA(self) -> np.ndarray:
        """Wavelength in Angstrom"""
        return self._wave

    @property
    def λ_um(self) -> np.ndarray:
        """Wavelength in micrometers"""
        return self.λ_AA * 1e-4

    @property
    def spectra(self) -> np.ndarray:
        """Spectra (n_templates, n_wave)"""
        return self._spectra


def load_sensitivity(
    filt: str, order: str, sens_dir: str | Path = SENS_CONF_DIR
) -> tuple[Callable[[npt.NDArray[np.float64]], npt.NDArray[np.float64]], Path]:
    """Interpolator for the aXe ETC sensitivity curve (Angstrom in, 0 outside).

    Parameters
    ----------
    filt : str
        Filter name (e.g. "F150W").
    order : str
        Order of the filter (e.g. "+1").
    sens_dir : str or Path, optional
        Directory containing the sensitivity curve files.
        Defaults to `SENS_CONF_DIR`.

    Returns
    -------
    Callable[[npt.NDArray[np.float64]], npt.NDArray[np.float64]]
        Interpolator function for the sensitivity curve.
    Path
        Path to the sensitivity curve file.
    """
    tag = ORDER_SENS_TAG.get(order)
    if tag is None:
        raise ValueError(
            f"No sensitivity curve available for order {order!r}; "
            f"supported orders: {list(ORDER_SENS_TAG)}"
        )
    logger.info(f"Loading sensitivity curve for {filt} {order} ({tag})...")
    logger.debug(f"sens_dir: {sens_dir}")
    logger.debug(
        f"glob pattern: {sens_dir}/**/NIRISS.GR150C.{filt}.{int(order)}.*.sens.fits"
    )

    path = Path(
        glob(f"{sens_dir}/**/NIRISS.GR150C.{filt}.{int(order)}.*.sens.fits")[0]
    )
    logger.debug(
        f"path: {sens_dir}/**/NIRISS.GR150C.{filt}.{int(order)}.*.sens.fits"
    )

    if not path.exists():
        raise FileNotFoundError(f"Sensitivity curve not found: {path}")

    with fits.open(path) as hdul:
        hdu = cast(fits.BinTableHDU, hdul[1])
        λs = np.asarray(hdu.data["WAVELENGTH"], dtype=float)
        sens = np.asarray(hdu.data["SENSITIVITY"], dtype=float)

    def interp(λ_AA):
        return np.interp(λ_AA, λs, sens, left=0.0, right=0.0)

    return interp, path


@dataclass
class SimulationAnalysisConfig:
    """Configuration for the simulation analysis."""

    basepath: Path
    """The base folder path to the simulation data."""
    direct_image: Path
    """The path to the direct image."""
    grism_image: Path
    """The path to the grism image."""
    catalog: Path
    """The path to the catalog."""
    simulation_configuration: dict = field(default_factory=dict)
    """The simulation configuration."""

    def __post_init__(self):
        assert self.direct_image.exists(), (
            f"Direct image not found: {self.direct_image}"
        )
        assert self.grism_image.exists(), (
            f"Grism image not found: {self.grism_image}"
        )
        assert self.catalog.exists(), f"Catalog not found: {self.catalog}"

    @classmethod
    def from_path(
        cls, basepath: Path, which_band: str
    ) -> "SimulationAnalysisConfig":
        """Get the paths to the simulated input data.

        Just a convenient loading function
        Data are stored in the `SIMULATED_DATA/output_{psf_type}/` directory as
        `sim_GR150C_{which_band}_{grism,direct}.fits

        Parameters
        ----------
        which_band : str
            The band to get the paths for.
        """
        with open(basepath / "simulation_configuration.yaml", "r") as f:
            conf = yaml.safe_load(f)

        return cls(
            basepath=basepath,
            direct_image=basepath / f"sim_GR150C_{which_band}_direct.fits",
            grism_image=basepath / f"sim_GR150C_{which_band}_grism.fits",
            catalog=basepath / "truth_catalog.ecsv",
            simulation_configuration=conf,
        )

    @property
    def orders(self):
        """The orders to use for the simulation."""
        return self.simulation_configuration["orders"]

    def get_grismtrace_from_crds(
        self,
        which_band: str,
    ) -> GrismTrace:
        """Get the grism trace from a CRDS specwcs file."""

        specwcs_file = glob_files(
            self.basepath, f"jwst_niriss_specwcs_*.GR150C.{which_band}.asdf"
        )[0]
        wavelength_file = glob_files(
            self.basepath, "jwst_niriss_wavelengthrange_0002.asdf"
        )[0]

        trace = GrismTrace.from_crds(
            str(specwcs_file),
            filter_name=which_band,
            wavelengthrange_file=str(wavelength_file),
            instrument="niriss",
        )
        return trace

    def get_sensitivity_curves(
        self, which_band: str, λ_AA: np.ndarray
    ) -> dict[str, np.ndarray]:
        """extract the sensitivity curve of that band interpolated at that wavelength

        Parameters
        ----------
        which_band : str
            The band to extract the sensitivity curve for.
        λ_AA : np.ndarray
            The wavelengths to interpolate the sensitivity curve at.

        Returns
        -------
        dict[str, np.ndarray]
            The sensitivity curve interpolated at the given wavelengths.
        """
        sensitivity = {}
        for order in self.orders:
            interp, path = load_sensitivity(
                which_band, order, sens_dir=SENS_CONF_DIR
            )
            sensitivity[order] = interp(λ_AA)
        return sensitivity


@dataclass
class AnalysisResults:
    """Bookkeeping for the simulation analysis results."""

    config: SimulationAnalysisConfig
    """Simulation analysis configuration information"""
    band: str
    """The band used for the analysis"""
    n_sources: int
    """The number of sources used in the analysis"""
    λ_AA: np.ndarray
    """The wavelengths used for the analysis in Angstroms"""
    model_grism: np.ndarray
    """The predicted model grism image (n_pixels x n_pixels)"""
    model_spectra: np.ndarray
    """The predicted model spectra (n_sources x n_wavelengths)"""
    model_fluxes: np.ndarray
    """The predicted model fluxes (n_sources)"""
    observed_grism: np.ndarray
    """The observed grism image (n_pixels x n_pixels)"""
    source_catalog: Table
    """The source catalog used for the analysis"""
    operator: JAXOperator
    """The operator used for the analysis"""
    sensitivity_curves: dict[str, np.ndarray]
    """The sensitivity curves {n_orders: n_wavelengths)"""
    other: dict = field(default_factory=dict)
    """Any other results or metadata from the analysis. Garbage collector here"""

    @property
    def observed_fluxes(self) -> np.ndarray:
        """The observed fluxes from the source catalog (n_sources)"""
        return self.source_catalog[f"flux_{self.band}"].data.astype(float)  # pyright: ignore

    @property
    def source_positions(self) -> np.ndarray:
        """The source positions from the source catalog (n_sources x 2)"""
        cat = self.source_catalog
        X = cat["x"].data.astype(float)  # pyright: ignore
        Y = cat["y"].data.astype(float)  # pyright: ignore
        return np.column_stack([Y, X])

    def grism_relative_residuals(self) -> float:
        r"""compute the image relative residual

        .. math::

            \\frac{\|model_{grism} - observed_{grism}\|}{\|observed_{grism}\|}

        """
        return float(
            np.linalg.norm(self.model_grism - self.observed_grism)
            / np.linalg.norm(self.observed_grism)
        )

    @property
    def residual_image(self) -> np.ndarray:
        # Normalise by a *global* robust flux scale, not per-pixel max(model, 1).
        # The old per-pixel form blew up every low-flux pixel (trace wings, gaps
        # between sources, background) to the raw data value, saturating the
        # residual colormap and painting bright "edges" that read as the model
        # being truncated.  With a global scale the residual is in units of
        # "fraction of typical bright flux", so wings (~1e-8 of peak) vanish
        # while genuine few-percent fit errors stay visible.
        obs = self.observed_grism
        positive = obs[obs > 0]
        scale = float(np.nanpercentile(positive, 99)) if positive.size else 1.0
        scale = max(scale, 1.0)
        return (obs - self.model_grism) / scale


def run_band(
    which_band: str,
    max_iter: int = 300,
    lam: float = 0.0,
):
    """Build a PSF-aware, CRDS-driven operator and fit one grism image.

    Returns a dict with the model, reconstructed spectra and a flux-recovery
    statistic against the truth catalog.
    """
    logger.info(f"🚀 Running band {which_band}")

    logger.info(
        f"Reading simulated input data information from {SIMULATED_DATA}"
    )
    simconfig = SimulationAnalysisConfig.from_path(SIMULATED_DATA, which_band)
    logger.debug(
        f"   direct image: {simconfig.direct_image} (we don't use it here)"
    )
    logger.debug(f"   grism image: {simconfig.grism_image}")
    logger.debug(f"   catalog: {simconfig.catalog}")
    logger.debug(
        f"   simulation configuration: {simconfig.simulation_configuration}"
    )
    logger.debug(f"   Simulations are for order(s): {simconfig.orders}")

    # we need to setup the mapping of tracings for this specific band
    logger.info(f"Getting the GrismTrace instance for band {which_band}")
    trace = simconfig.get_grismtrace_from_crds(which_band)

    # Get the wavelength range for the order in the image
    λlo_um, λhi_um = trace._lam_range(simconfig.orders[0], None, None)
    if λlo_um is None or λhi_um is None:
        raise ValueError("λlo_um or λhi_um is None")
    logger.debug(
        f"   {which_band} wavelength range for order {simconfig.orders[0]}: {λlo_um} - {λhi_um}"
    )
    λ_AA = np.linspace(
        max(float(λlo_um) * 1e4, 7000.0),
        # clamp to the PCA basis max wavelength (regenerated kurucz_pca.csv
        # spans 0.7–2.3 µm = 7000–23000 Å); otherwise from_csv raises.
        min(float(λhi_um) * 1e4, 23000.0),
        150,
    )
    logger.debug(
        f"   Assumming 150 linear samples of wavelengths: {λ_AA.shape} values"
    )

    # Get the sensitivity curve for this band and these wavelengths
    logger.info(
        f"Getting the sensitivity curve for band {which_band} and order {simconfig.orders[0]}"
    )
    sensitivity_curves = simconfig.get_sensitivity_curves(which_band, λ_AA)

    # Get the dispersed image / the grism image
    logger.info(f"Reading grism image {simconfig.grism_image}")
    with fits.open(simconfig.grism_image) as hdul:
        hdu = cast(fits.PrimaryHDU, hdul[0])
        grism = np.asarray(hdu.data, dtype=float)
        fwhm = float(hdu.header.get("FWHM", 1.6))  # pyright: ignore
    n_rows, n_cols = grism.shape
    sigma_psf = fwhm / 2.355  # 2 sqrt(2*ln(2))  -- Gaussian conversion factor
    logger.debug(f"    Image shape: {n_rows} x {n_cols}")
    logger.debug(f"    PSF sigma: {sigma_psf}")

    # Get the source catalog to get the source positions
    logger.info(f"Reading source catalog {simconfig.catalog}")
    cat = Table.read(simconfig.catalog)
    X = cat["x"].data.astype(float)  # column
    Y = cat["y"].data.astype(float)  # row
    n_sources = len(X)
    source_positions = np.column_stack([Y, X])
    logger.debug(f"    Found {n_sources} sources in catalog")

    logger.info("Model preparation...")
    logger.debug("    Setting up CRDSConfig with the above")

    config = CRDSConfig(
        grism="GR150C",
        filter_name=which_band,
        wavelengths=λ_AA,
        orders=simconfig.orders,
        sensitivity=sensitivity_curves,
        trace=trace,
        psf_stamp_size=7,
    )

    # Get the eigenspectra basis. This is a PCA basis of Kurucz spectra to represent stars
    eigenspectra_source = simconfig.basepath / "kurucz_pca.csv"
    logger.info(f"Getting the eigenspectra basis from {eigenspectra_source}")
    # Fixed PCA to include the mean spectrum data[:, 1]
    basis = EigenspectraBasis.from_csv(eigenspectra_source, λ_AA)

    # composing operators: PSF-aware forward model
    logger.info("Building Image model operator (GaussianPSFOperator)")
    # Build the PSF *into* the forward model by scattering a 2D Gaussian stamp
    # at each (sub-pixel) trace point — this matches the simulation's forward
    # model and avoids the sub-pixel aliasing a point delta + Gaussian blur
    # leaves along the dispersion direction.
    op = GaussianPSFOperator.build(
        config,
        basis,
        grism.shape,
        source_positions,
        psf_sigma=sigma_psf,
        stamp_size=config.psf_stamp_size,
    )

    print("Fitting...")
    logger.info(
        f"Building solver JAXProximalSolver(max_iter={max_iter}, lam={lam})"
    )
    # use the JAX solver to fit the image
    solver = JAXProximalSolver(
        op, noise_model=None, lam=lam, max_iter=max_iter
    )
    # internally we solve on the flat array
    f_flat = grism.ravel().astype(float)
    # scale normalization needed for the solver stability
    scale = float(np.percentile(grism[grism > 0], 90))

    logger.info("Solving for image solution...")
    _fitting_start = time()
    a = solver.solve(f_flat / scale) * scale
    _fitting_end = time()
    logger.info(
        f"    Fitting Done. (took {_fitting_end - _fitting_start:.2f}s)"
    )

    logger.info("Extracting spectra...")
    # compute the psf convolved model image
    model = op.apply(a).astype(float).reshape(n_rows, n_cols)
    # compute the spectra source by source
    coeff = a.reshape(-1, basis.n_components)
    spectra = basis.reconstruct(coeff)
    # sum over the wavelength axis to get the predicted fluxes
    # FIXME: flux_proxy = np.trapz(spectra, x=wavelengths, axis=1)
    flux_proxy = spectra.sum(axis=1)

    result = AnalysisResults(
        config=simconfig,
        band=which_band,
        n_sources=n_sources,
        λ_AA=λ_AA,
        model_grism=model,
        model_spectra=spectra,
        model_fluxes=flux_proxy,
        observed_grism=grism,
        source_catalog=cat,
        operator=op,
        sensitivity_curves=sensitivity_curves,
    )

    # Compute some performance statistics / values
    logger.info("Finding and flagging isolated sources.")
    # find isolated sources to help comparison later
    # isolated source = no nearby neighbors (within 60 pixels)
    tree = cKDTree(np.column_stack([X, Y]))
    d2, _ = tree.query(np.column_stack([X, Y]), k=2)
    isolated = d2[:, 1] > 60  # arbitrary threshold
    result.other["is_isolated"] = isolated
    logger.info(f"Found {isolated.astype(int).sum()} isolated sources.")

    # blind direct extraction (isolated sources only)
    logger.info("Extracting spectra from the grism image when isolated...")
    direct = np.full((n_sources, len(λ_AA)), np.nan)
    for k in np.where(isolated)[0]:
        direct[k] = direct_extract_source(
            grism,
            op._trace_indices[k, 0],  # pyright: ignore
            sigma_psf,
            n_rows,
            n_cols,
        )
    result.other["isolated_direct_spectra"] = direct

    logger.info("Extracting original kurucz spectra per simulated source...")
    kurucz_basis = SpectralBasis(
        original_spectra_path=simconfig.basepath / "kurucz_spectra.csv"
    )
    ki = cat["kurucz_index"].data.astype(int)
    orig = np.empty((n_sources, len(λ_AA)))
    for k in range(n_sources):
        orig[k] = np.interp(
            λ_AA, kurucz_basis.λ_AA, kurucz_basis.spectra[ki[k]]
        )
    result.other["original_spectra"] = orig

    # fit proxy vs. truth for isolated sources
    # compute the linear fit to the proxy vs. truth for isolated sources
    # compute the R^2 value for the fit
    logger.info("Fitting proxy vs. truth for isolated sources...")
    truth_flux = result.observed_fluxes
    c = np.polyfit(flux_proxy[isolated], truth_flux[isolated], 1)[0]
    pred = c * flux_proxy[isolated]
    r2 = 1.0 - np.sum((truth_flux[isolated] - pred) ** 2) / np.sum(
        (truth_flux[isolated] - truth_flux[isolated].mean()) ** 2
    )
    result.other["r2_isolated"] = r2
    logger.info(f"    R^2 = {r2:.3f}")

    # add bookkeeping
    result.other.update(
        {
            "a": a,
            "base_op": op,
            "basis": basis,
            "op": op,
            "c": c,
            "sigma_psf": sigma_psf,
            "n_rows": n_rows,
            "n_cols": n_cols,
        }
    )

    return result


